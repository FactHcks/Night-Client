package me.night.mixin;

import me.night.ui.glass.ChatPanel;
import net.minecraft.client.font.TextRenderer;
import net.minecraft.client.gui.DrawContext;
import net.minecraft.client.gui.hud.ChatHud;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;

@Mixin(ChatHud.class)
public class MixinChatHud {
    @Inject(method = "render(Lnet/minecraft/client/gui/DrawContext;Lnet/minecraft/client/font/TextRenderer;IIIZZ)V", at = @At("HEAD"))
    private void night$panel(DrawContext context, TextRenderer textRenderer, int currentTick, int mouseX, int mouseY,
                             boolean focused, boolean flag, CallbackInfo ci) {
        if (ChatPanel.enabled()) ChatPanel.drawAndReset(context);
    }
}
